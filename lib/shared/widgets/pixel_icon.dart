import 'package:flutter/material.dart';

/// Motor genérico para dibujar cualquier ícono como una cuadrícula de
/// píxeles (0/1), en vez del glifo vectorial de Material Icons — mismo
/// mecanismo que PixelF5Logo y PixelChatIcon, generalizado para
/// cualquier máscara. Los diseños concretos viven en [PixelIcons].
class PixelIcon extends StatelessWidget {
  const PixelIcon(this.mask, {super.key, this.size = 20, this.color});

  final List<List<int>> mask;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final rows = mask.length;
    final cols = mask.map((r) => r.length).reduce((a, b) => a > b ? a : b);
    final longestSide = rows > cols ? rows : cols;
    final pixelSize = size / longestSide;
    final resolvedColor =
        color ?? IconTheme.of(context).color ?? Theme.of(context).colorScheme.onSurface;

    return SizedBox(
      width: cols * pixelSize,
      height: rows * pixelSize,
      child: Stack(
        children: [
          for (var row = 0; row < rows; row++)
            for (var col = 0; col < mask[row].length; col++)
              if (mask[row][col] == 1)
                Positioned(
                  left: col * pixelSize,
                  top: row * pixelSize,
                  width: pixelSize,
                  height: pixelSize,
                  child: ColoredBox(color: resolvedColor),
                ),
        ],
      ),
    );
  }
}

